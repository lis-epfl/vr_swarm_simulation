using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// The landmarks round a city, so a pilot who sees the world only through the drones' feeds has something fixed to
/// orient by: a snow-capped mountain range to the south, a lake in front of green hills to the north, a wind farm on a
/// ridge to the east and a red-and-white TV mast to the west, in line with the spawn road. They stand beyond the city
/// on a ring of Terrain tiles of their own. This component sits on the root of <c>Assets/Landmarks/Landmarks.prefab</c>,
/// which <c>LandmarkBuilder</c> (<c>Tools/Swarm/Landmarks</c>) makes and places; the reasons for every size and position
/// are there.
///
/// <para>At Play it turns the turbine rotors and blinks the mast's beacons, and nothing else. Nothing in the set has a
/// collider except its ground (on Default, like the city's own), so no landmark is an obstacle, a raycast target or
/// part of the analysis.</para>
///
/// <para><b>The mast and the turbines take Asset Store models.</b> Set a model slot and press <i>Place models</i> in the
/// inspector: the model goes onto every spot, snapped to the ground, scaled to the generated one's height, with its
/// colliders removed, its layers set to Default and its shadows off. Clear the slot and press it again to get the
/// generated one back. The mountain, the hills and the ridge are sculpted with the ordinary Terrain tools, and the
/// lake's shoreline is the spline on <see cref="LakeOutline"/>.</para>
/// </summary>
[DisallowMultipleComponent]
public class LandmarkSet : MonoBehaviour
{
    /// <summary>The child of a spot that holds its model, generated or not.</summary>
    public const string ModelName = "Model";

    [Header("Models (empty: the generated ones)")]
    [Tooltip("A mast or tower for the TV mast's spot. Press Place models after changing it.")]
    public GameObject mastModel;
    [Tooltip("A wind turbine for every Turbine spot. Press Place models after changing it.")]
    public GameObject turbineModel;
    [Tooltip("Scale a model so it stands as tall as the generated one (mast 300 m, turbine tip 150 m).")]
    public bool fitModelHeight = true;
    [Tooltip("Degrees added about the vertical, for a model whose front is not its +Z.")]
    public float mastModelYaw = 0f;
    [Tooltip("Degrees added about the vertical, for a model whose rotor does not face its +Z. The spots face the city.")]
    public float turbineModelYaw = 0f;

    [Header("Rotors")]
    [Tooltip("The child of each turbine that turns, found at any depth. Empty: nothing is turned (a model that " +
             "animates itself).")]
    public string rotorName = "Rotor";
    [Tooltip("The axis the rotor turns about, in the rotor's own frame.")]
    public Vector3 rotorAxis = Vector3.forward;
    public float rotorRpm = 12f;

    [Header("Beacons")]
    [Tooltip("The mast's lights, shown for beaconOnSeconds of every beaconPeriod.")]
    public Renderer[] beacons = new Renderer[0];
    public float beaconPeriod = 1.5f;
    public float beaconOnSeconds = 0.5f;

    [Header("Layout (written by the builder)")]
    [Tooltip("Parent of the Turbine spots.")]
    public Transform windFarm;
    [Tooltip("The TV mast's spot.")]
    public Transform mast;
    [Tooltip("Parent of the ring's Terrain tiles.")]
    public Transform ground;
    [Tooltip("The city the set stands round, for Check: its centre (x, z) and half its arena's side (m).")]
    public Vector2 cityCentre = Vector2.zero;
    public float cityHalfExtent = 365f;
    /// <summary>The version of <c>LandmarkBuilder</c>'s ground generator the ring's tiles were last generated by (0:
    /// before versions), so <i>Add to open scene</i> can offer to regenerate ground the generator has since changed.</summary>
    [HideInInspector] public int groundVersion;

    private Transform[] rotors = new Transform[0];
    private Quaternion[] rotorRest = new Quaternion[0];

    void Awake() => FindRotors();

    void Update() => Animate(Time.time);

    /// <summary>Finds every spot's rotor and its rest pose.</summary>
    public void FindRotors()
    {
        var found = new List<Transform>();
        if (windFarm != null && !string.IsNullOrEmpty(rotorName))
        {
            foreach (Transform spot in windFarm)
            {
                Transform r = FindDeep(spot, rotorName);
                if (r != null) found.Add(r);
            }
        }
        rotors = found.ToArray();
        rotorRest = new Quaternion[rotors.Length];
        for (int i = 0; i < rotors.Length; i++) rotorRest[i] = rotors[i].localRotation;
    }

    /// <summary>The set as it stands at time <paramref name="t"/> (s): each rotor at its own phase, so the farm does not
    /// turn in lockstep, and the beacons on or off.</summary>
    public void Animate(float t)
    {
        float degreesPerSecond = rotorRpm * 6f;
        for (int i = 0; i < rotors.Length; i++)
        {
            if (rotors[i] == null) continue;
            float angle = Mathf.Repeat(t * degreesPerSecond + i * 47f, 360f);
            rotors[i].localRotation = rotorRest[i] * Quaternion.AngleAxis(angle, rotorAxis);
        }
        bool on = beaconPeriod > 0f && Mathf.Repeat(t, beaconPeriod) < beaconOnSeconds;
        foreach (Renderer b in beacons)
        {
            if (b != null) b.enabled = on;
        }
    }

    /// <summary>The first descendant of <paramref name="t"/> called <paramref name="name"/> (not t itself), or null.</summary>
    public static Transform FindDeep(Transform t, string name)
    {
        foreach (Transform c in t)
        {
            if (c.name == name) return c;
            Transform r = FindDeep(c, name);
            if (r != null) return r;
        }
        return null;
    }
}
